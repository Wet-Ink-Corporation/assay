#!/usr/bin/env bash
# Adds GitHub's native "blocked by" links for the assay v1 plan (mirrors each issue's Blocked by checklist).
# Needs gh authenticated with write access. Safe to re-run: existing links are reported and skipped.
set -uo pipefail
R=Wet-Ink-Corporation/assay
link() { # link <issue> <blocker>
  local id; id=$(gh api "repos/$R/issues/$2" --jq .id) || { echo "#$1 <- #$2: could not read #$2"; return; }
  if gh api -X POST "repos/$R/issues/$1/dependencies/blocked_by" -F issue_id="$id" >/dev/null 2>&1; then echo "#$1 <- #$2 linked"; else echo "#$1 <- #$2 skipped (exists or failed)"; fi
}
