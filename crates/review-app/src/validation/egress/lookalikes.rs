/// `c` read as the ASCII letter or digit it is drawn as, or `c` itself.
///
/// Cost: a binary search of [`LOOKALIKES`], a constant.
pub(super) fn read(c: char) -> char {
    ascii_of(c).unwrap_or(c)
}

/// The ASCII letter or digit `c` is drawn as, if [`LOOKALIKES`] lists it.
pub(super) fn ascii_of(c: char) -> Option<char> {
    match LOOKALIKES.binary_search_by_key(&c, |&(lookalike, _)| lookalike) {
        Ok(at) => LOOKALIKES.get(at).map(|&(_, ascii)| ascii),
        Err(_) => None,
    }
}

#[cfg(test)]
mod tests {
    use proptest::prelude::*;

    use super::super::EgressToken;
    use super::{LOOKALIKES, ascii_of};

    #[test]
    fn the_table_is_sorted_and_reads_non_ascii_as_ascii() {
        let unsorted = LOOKALIKES
            .windows(2)
            .filter(|pair| pair[0].0 >= pair[1].0)
            .count();
        let not_ascii = LOOKALIKES
            .iter()
            .filter(|&&(c, ascii)| c.is_ascii() || !ascii.is_ascii_alphanumeric())
            .count();

        assert_eq!((unsorted, not_ascii), (0, 0));
    }

    #[test]
    fn reads_a_character_from_each_source() {
        // NFD, names (stroke, small capital, dotless, superscript), NFKC (mathematical,
        // fullwidth, enclosed), decimal, and confusables (Cyrillic, Greek, Lisu, Cherokee).
        let characters = [
            '\u{e9}',
            '\u{167}',
            '\u{1d00}',
            '\u{131}',
            '\u{b2}',
            '\u{1d400}',
            '\u{ff10}',
            '\u{24b6}',
            '\u{663}',
            '\u{430}',
            '\u{3b1}',
            '\u{a4ee}',
            '\u{13aa}',
        ];

        assert_eq!(
            characters.map(ascii_of),
            [
                'e', 't', 'a', 'i', '2', 'A', '0', 'A', '3', 'a', 'a', 'a', 'A'
            ]
            .map(Some)
        );
    }

    #[test]
    fn leaves_skeletons_that_could_be_several_letters_unread() {
        // Cyrillic capital I (`I`, `l` or `1`) and Greek capital omicron (`O` or `0`).
        assert_eq!(['\u{406}', '\u{39f}'].map(ascii_of), [None, None]);
    }

    /// The characters of `ranges` the table reads as an ASCII letter or digit, the first for
    /// each, as `(ascii, lookalike)`.
    fn alphabet(ranges: &[(u32, u32)]) -> Vec<(char, char)> {
        let mut alphabet: Vec<(char, char)> = Vec::new();
        for &(lookalike, ascii) in &LOOKALIKES {
            let inside = ranges
                .iter()
                .any(|&(first, last)| (first..=last).contains(&u32::from(lookalike)));
            if inside && !alphabet.iter().any(|&(taken, _)| taken == ascii) {
                alphabet.push((ascii, lookalike));
            }
        }
        alphabet
    }

    /// Stroked and barred Latin letters, `a` to `z` but `m`, `w` and `x`.
    const STROKED: &str = "\u{2c65}\u{180}\u{23c}\u{111}\u{247}\u{a799}\u{1e5}\u{127}\u{268}\u{249}\u{a741}\u{142}\u{a7a5}\u{f8}\u{a751}\u{a757}\u{24d}\u{a7a9}\u{167}\u{289}\u{a75f}\u{24f}\u{1b6}";

    /// Every lookalike alphabet: stroked Latin, Lisu, Cherokee, Cyrillic, Greek, mathematical,
    /// fullwidth, and Latin with dots and other marks.
    fn alphabets() -> Vec<Vec<(char, char)>> {
        let stroked = STROKED
            .chars()
            .filter_map(|c| Some((ascii_of(c)?, c)))
            .collect();
        vec![
            stroked,
            alphabet(&[(0xa4d0, 0xa4ff)]),
            alphabet(&[(0x13a0, 0x13ff), (0xab70, 0xabbf)]),
            alphabet(&[(0x400, 0x4ff)]),
            alphabet(&[(0x370, 0x3ff)]),
            alphabet(&[(0x1d400, 0x1d7ff)]),
            alphabet(&[(0xff00, 0xffef)]),
            alphabet(&[(0x1e00, 0x1eff)]),
        ]
    }

    /// `token` with each character an alphabet has a lookalike for (same case first) replaced,
    /// and a space after every 15 characters.
    fn respelled(token: &str, alphabet: &[(char, char)]) -> String {
        token
            .chars()
            .map(|c| {
                alphabet
                    .iter()
                    .find(|&&(ascii, _)| ascii == c)
                    .or_else(|| {
                        alphabet
                            .iter()
                            .find(|&&(ascii, _)| ascii.eq_ignore_ascii_case(&c))
                    })
                    .map_or(c, |&(_, lookalike)| lookalike)
            })
            .enumerate()
            .flat_map(|(at, c)| {
                (at > 0 && at % 15 == 0)
                    .then_some(' ')
                    .into_iter()
                    .chain([c])
            })
            .collect()
    }

    const BASE64URL: &str = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";

    proptest! {
        #[test]
        fn catches_a_realistic_token_respelled_through_each_alphabet(
            body in prop::collection::vec(
                prop::sample::select(BASE64URL.chars().collect::<Vec<_>>()),
                95,
            )
        ) {
            let token: String = "sk-ant-oat01-".chars().chain(body).collect();
            let scan = EgressToken::new(&token).expect("a realistic token is long enough");
            for alphabet in alphabets() {
                let text = respelled(&token, &alphabet);
                prop_assert!(scan.is_in(&text), "missed {}", text);
            }
        }
    }
}
