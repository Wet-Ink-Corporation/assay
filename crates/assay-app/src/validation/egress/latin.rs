/// The Latin blocks whose letters are refused when [`PRECOMPOSED`] has no base for them:
/// ordinal indicators, Latin-1 Supplement and Extended-A and -B, IPA Extensions, Latin Extended
/// Additional, -C, -D and -E, and the Latin ligatures.
const LATIN_RANGES: [(char, char); 9] = [
    ('\u{aa}', '\u{aa}'),
    ('\u{ba}', '\u{ba}'),
    ('\u{c0}', '\u{2af}'),
    ('\u{1e00}', '\u{1eff}'),
    ('\u{2c60}', '\u{2c7f}'),
    ('\u{a720}', '\u{a7ff}'),
    ('\u{ab30}', '\u{ab6f}'),
    ('\u{fb00}', '\u{fb06}'),
    ('\u{1df00}', '\u{1dfff}'),
];

/// `c` with a precomposed Latin letter read as its base ASCII letter (case kept) and a
/// superscript or subscript digit as its ASCII digit; any other character unchanged.
///
/// Cost: a binary search of [`PRECOMPOSED`], a constant.
pub(super) fn fold_char(c: char) -> char {
    base_letter(c).or_else(|| script_digit(c)).unwrap_or(c)
}

/// Whether `c` is a non-ASCII letter of a Latin block that [`PRECOMPOSED`] cannot read back
/// (`ß`, `ø`, `ł`, `ɐ`): drawn from the Latin script, but with no ASCII base to compare.
pub(super) fn is_unmapped_latin(c: char) -> bool {
    !c.is_ascii()
        && c.is_alphabetic()
        && LATIN_RANGES
            .iter()
            .any(|&(first, last)| (first..=last).contains(&c))
        && base_letter(c).is_none()
}

/// The ASCII digit a superscript or subscript digit (`²`, `³`, `¹`, U+2070-2089) is drawn as.
pub(super) fn script_digit(c: char) -> Option<char> {
    let value = match c {
        '\u{b9}' => 1,
        '\u{b2}' => 2,
        '\u{b3}' => 3,
        '\u{2070}' => 0,
        '\u{2074}'..='\u{2079}' | '\u{2080}'..='\u{2089}' => u32::from(c) % 16,
        _ => return None,
    };
    char::from_digit(value, 10)
}

/// The base ASCII letter of a precomposed Latin letter in [`PRECOMPOSED`].
fn base_letter(c: char) -> Option<char> {
    match PRECOMPOSED.binary_search_by_key(&c, |&(letter, _)| letter) {
        Ok(at) => PRECOMPOSED
            .get(at)
            .and_then(|(_, decomposed)| decomposed.chars().next()),
        Err(_) => None,
    }
}

#[cfg(test)]
mod tests {
    use super::{PRECOMPOSED, fold_char, is_unmapped_latin, script_digit};

    #[test]
    fn reads_a_letter_of_each_block_as_its_base() {
        // Latin-1 Supplement, Extended-A, Extended-B, Extended Additional; both cases.
        let letters = [
            '\u{e9}', '\u{d1}', '\u{101}', '\u{17d}', '\u{1ce}', '\u{218}', '\u{1ea1}', '\u{1ef4}',
        ];

        assert_eq!(
            letters.map(fold_char),
            ['e', 'N', 'a', 'Z', 'a', 'S', 'a', 'Y']
        );
    }

    #[test]
    fn every_entry_decomposes_to_an_ascii_letter_and_diacritics() {
        let in_blocks =
            |c: char| ('\u{c0}'..='\u{24f}').contains(&c) || ('\u{1e00}'..='\u{1eff}').contains(&c);
        let wrong: Vec<char> = PRECOMPOSED
            .iter()
            .filter(|(letter, decomposed)| {
                let mut chars = decomposed.chars();
                let base = chars.next();
                let marks: Vec<char> = chars.collect();
                !(in_blocks(*letter)
                    && base.is_some_and(|base| base.is_ascii_alphabetic())
                    && !marks.is_empty()
                    && marks
                        .iter()
                        .all(|mark| ('\u{300}'..='\u{36f}').contains(mark))
                    && base.is_some_and(|base| letter.is_uppercase() == base.is_ascii_uppercase()))
            })
            .map(|(letter, _)| *letter)
            .collect();

        assert_eq!(wrong, Vec::<char>::new());
    }

    #[test]
    fn the_table_is_sorted_without_repeats() {
        assert!(
            PRECOMPOSED.windows(2).all(|pair| pair[0].0 < pair[1].0),
            "PRECOMPOSED must be strictly sorted for its binary search"
        );
    }

    #[test]
    fn reads_superscript_and_subscript_digits_as_digits() {
        let digits = [
            '\u{b9}', '\u{b2}', '\u{b3}', '\u{2070}', '\u{2074}', '\u{2079}', '\u{2080}',
            '\u{2089}', '\u{2071}',
        ];

        assert_eq!(
            digits.map(script_digit),
            [
                Some('1'),
                Some('2'),
                Some('3'),
                Some('0'),
                Some('4'),
                Some('9'),
                Some('0'),
                Some('9'),
                None
            ]
        );
    }

    #[test]
    fn refuses_latin_letters_without_an_ascii_base_only() {
        let unmapped = ['\u{df}', '\u{f8}', '\u{142}', '\u{250}', '\u{fb01}'];
        let other = ['\u{e9}', 'a', '\u{436}', '\u{d7}', '\u{4e2d}'];

        assert_eq!(
            (
                unmapped.map(is_unmapped_latin),
                other.map(is_unmapped_latin)
            ),
            ([true; 5], [false; 5])
        );
    }
}
